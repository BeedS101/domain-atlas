#!/usr/bin/env node
// Stamps the shared site chrome (terms link footer, experimental-risk notice, styles) into the static pages and
// generates each domain's /terms/ page from one source. Development-time only: the output is plain static HTML,
// so shared hosting needs no Node, no PHP include and no build step.
//
//   node tools/site-chrome.js           write: update every page listed in site-shared/pages.json
//   node tools/site-chrome.js --check   exit 1 if any page is out of date, uncovered, or has a duplicate notice
//
// Sources (site-shared/): terms-content.html (the terms text), terms-page.html (shell of the /terms/ page),
// footer.html, risk-notice.html, site.css, pages.json (which page gets what). A stamped page carries marker
// comments (atlas-site:<region>:start/end) around each generated region, so re-running replaces the region in place.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SHARED = path.join(ROOT, 'site-shared');
const read = (p) => fs.readFileSync(p, 'utf8');
const trimEnd = (s) => s.replace(/\s+$/, '');

function loadSources() {
  const css = trimEnd(read(path.join(SHARED, 'site.css')));
  return {
    config: JSON.parse(read(path.join(SHARED, 'pages.json'))),
    head: '<style>\n' + css + '\n</style>',
    footer: trimEnd(read(path.join(SHARED, 'footer.html'))),
    notice: trimEnd(read(path.join(SHARED, 'risk-notice.html'))),
    termsContent: trimEnd(read(path.join(SHARED, 'terms-content.html'))),
    termsShell: read(path.join(SHARED, 'terms-page.html')),
  };
}

const marker = (region, edge) => '<!-- atlas-site:' + region + ':' + edge + ' -->';
const block = (region, body) => marker(region, 'start') + '\n' + body + '\n' + marker(region, 'end');
const regionRe = (region) => new RegExp('[ \\t]*' + marker(region, 'start').replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + marker(region, 'end').replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?', 'g');

// Replaces the region if the page already has one; otherwise inserts it at the anchor. A region that appears twice
// is an error (a duplicate footer), not something to paper over.
function setRegion(html, region, body, where) {
  const re = regionRe(region);
  const found = html.match(re) || [];
  if (found.length > 1) throw new Error('duplicate "' + region + '" region');
  if (found.length === 1) return html.replace(re, () => block(region, body) + '\n');
  if (where === 'before-head-close') return insertBefore(html, /<\/head>/i, block(region, body) + '\n');
  if (where === 'after-body-open') return insertAfter(html, /<body\b[^>]*>/i, '\n' + block(region, body));
  if (where === 'before-body-close') return insertBefore(html, /<\/body>/i, block(region, body) + '\n', true);
  throw new Error('unknown anchor ' + where);
}
function insertBefore(html, re, text, last) {
  let idx = -1;
  if (last) { let m; const g = new RegExp(re.source, 'gi'); while ((m = g.exec(html))) idx = m.index; } else { const m = re.exec(html); idx = m ? m.index : -1; }
  if (idx < 0) throw new Error('anchor ' + re + ' not found');
  return html.slice(0, idx) + text + html.slice(idx);
}
function insertAfter(html, re, text) {
  const m = re.exec(html);
  if (!m) throw new Error('anchor ' + re + ' not found');
  const end = m.index + m[0].length;
  return html.slice(0, end) + text + html.slice(end);
}
function removeRegion(html, region) { return html.replace(regionRe(region), ''); }

function stampPage(html, wantsNotice, src) {
  let out = setRegion(html, 'head', src.head, 'before-head-close');
  out = wantsNotice ? setRegion(out, 'notice', src.notice, 'after-body-open') : removeRegion(out, 'notice');
  return setRegion(out, 'footer', src.footer, 'before-body-close');
}

function termsPage(src) {
  let out = src.termsShell.replace('{{CONTENT}}', () => src.termsContent);
  out = out.replace(regionRe('head'), () => block('head', src.head) + '\n').replace(regionRe('footer'), () => block('footer', src.footer) + '\n');
  return '<!-- Generated by tools/site-chrome.js from site-shared/. Edit the sources there and re-run; do not edit this file. -->\n' + out;
}

// Every HTML file that could be served to a visitor must be listed, or excluded with a reason.
function listHtml(dir, out) {
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = dir ? dir + '/' + e.name : e.name;
    if (e.isDirectory()) { if (!['node_modules', '.git'].includes(e.name)) listHtml(rel, out); }
    else if (/\.html?$/i.test(e.name)) out.push(rel);
  }
  return out;
}
function coverage(src) {
  const c = src.config;
  const listed = new Set([].concat(c.notice, c.footerOnly, c.termsPages));
  const problems = [];
  for (const f of listed) if (!fs.existsSync(path.join(ROOT, f)) && !c.termsPages.includes(f)) problems.push('listed page is missing: ' + f);
  const excluded = Object.keys(c.excluded);
  for (const f of listHtml('', [])) {
    if (listed.has(f)) continue;
    if (excluded.some((x) => f === x || (x.endsWith('/') && f.startsWith(x)))) continue;
    problems.push('page is neither covered nor excluded: ' + f);
  }
  return problems;
}

function main() {
  const check = process.argv.includes('--check');
  const src = loadSources();
  const problems = coverage(src);
  if (problems.length && !check) { console.error(problems.join('\n')); process.exit(1); }
  const changed = [];
  const apply = (rel, expected) => {
    const file = path.join(ROOT, rel);
    const current = fs.existsSync(file) ? read(file) : null;
    if (current === expected) return;
    changed.push(rel);
    if (!check) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, expected); }
  };
  for (const rel of src.config.termsPages) apply(rel, termsPage(src));
  for (const [list, notice] of [[src.config.notice, true], [src.config.footerOnly, false]]) {
    for (const rel of list) {
      const file = path.join(ROOT, rel);
      if (!fs.existsSync(file)) continue;
      try { apply(rel, stampPage(read(file), notice, src)); } catch (e) { problems.push(rel + ': ' + e.message); }
    }
  }
  if (check) {
    for (const rel of changed) problems.push('out of date, run node tools/site-chrome.js: ' + rel);
    if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
    console.log('site chrome is up to date: ' + (src.config.notice.length + src.config.footerOnly.length) + ' pages, ' + src.config.termsPages.length + ' terms pages');
    return;
  }
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(changed.length ? 'updated:\n  ' + changed.join('\n  ') : 'nothing to update');
}
main();
