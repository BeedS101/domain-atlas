// Manual check for demo-domain-a/attestation-demo.html — the standalone,
// extension-free page for SPEC.md §5.11 (third-party attestations): a
// signer with no part in issuing an asset independently signs its own
// opinion about it, with no cooperation, custody, or shared infrastructure
// needed from whoever issued the thing being reviewed.
//
// Earlier versions of this page demoed that with two real, separately-
// running domains (one issuing the filing, a second playing the reviewer),
// which meant this test had to spin up two isolated issuer-server
// instances on fixed ports 8001/8002 to match the page's own hardcoded
// REVIEWER_BASE. Bruno reported that setup doesn't work once actually
// deployed to a single live domain (evtec.co.za): a browser resolves
// http://localhost:8002 to whatever machine is VIEWING the page, not to a
// real second domain. The page now instead uses this SAME domain's own
// second, independent keypair (published at
// .well-known/atlas-reviewer-key.json, generated by issuer-server/
// server.js's loadOrCreateReviewerKeypair(), signed with by
// signAsReviewer()) to stand in for "the independent reviewer" — genuinely
// a different key, fetched and verified separately from the one that
// issues the filing, but living on one running instance, so this test now
// only needs ONE isolated instance, same as manual-business-demo.js/
// manual-warranty-demo.js.
//
// Checks:
//   1. Clicking "Get my demo filing" issues a real atlas.demo.attestation.
//      filing credential and renders it.
//   2. Clicking "Mark 'Reviewed'" calls this same domain's own
//      /atlas/demo/attestation/issue and renders a real attestation
//      credential — same issuer.domain as the filing, but a genuinely
//      different issuer.publicKey, proving it's a second, independent key
//      and not a relabeled copy of the filing's own signature.
//   3. "Try verifying this one independently" on the attestation fetches
//      this domain's own atlas-reviewer-key.json (not atlas-key.json) and
//      reports it valid.
//   4. Tampering with the pasted attestation JSON (changing `claim`)
//      before clicking Verify again correctly reports it invalid — proving
//      the check is a real signature check, not an id lookup.
//   5. "Revoke this attestation" succeeds, and the page immediately
//      re-verifies the same attestation as revoked by the reviewer key.
//   6. The underlying filing itself still independently verifies as valid
//      after the attestation above it was revoked — the two are genuinely
//      independent.
//
// Not part of the permanent suite, same reasoning as the other
// manual-*.js scripts.

const { chromium } = require('playwright');
const { spawn } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const NODE_PORT = 8146; // isolated — distinct from every other manual-*.js test's chosen port
const NODE_DOMAIN = 'localhost:' + NODE_PORT;
const NODE_BASE = 'http://' + NODE_DOMAIN;

const NODE_STATE_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'atlas-attestation-demo-node-'));
const NODE_DOCROOT_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'atlas-attestation-demo-docroot-'));

function assert(cond, message) {
  if (!cond) throw new Error('ASSERTION FAILED: ' + message);
}

(async () => {
  console.log('SETUP: copying demo-domain-a into an isolated docroot and starting its own issuer-server instance on port ' + NODE_PORT);
  fs.cpSync(path.resolve(__dirname, '..', 'demo-domain-a'), NODE_DOCROOT_DIR, { recursive: true });
  const nodeProc = spawn('node', ['issuer-server/server.js'], {
    cwd: path.resolve(__dirname, '..'),
    env: { ...process.env, PORT: String(NODE_PORT), ATLAS_DOMAIN: NODE_DOMAIN, ATLAS_STATE_DIR: NODE_STATE_DIR, ATLAS_DOCROOT: NODE_DOCROOT_DIR },
    stdio: ['ignore', 'pipe', 'pipe']
  });
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('issuer-server did not start in time')), 10000);
    nodeProc.stdout.on('data', (d) => { if (d.toString().includes('listening')) { clearTimeout(timer); resolve(); } });
    nodeProc.on('exit', (code) => reject(new Error('issuer-server exited early with code ' + code)));
  });
  console.log('PASS: isolated issuer-server up on port ' + NODE_PORT + ', serving the isolated demo-domain-a copy');

  let browser;
  try {
    browser = await chromium.launch({ headless: true, executablePath: '/opt/pw-browsers/chromium' });
    const page = await browser.newPage();
    await page.goto(NODE_BASE + '/attestation-demo.html', { waitUntil: 'load' });

    console.log('STEP 1: clicking "Get my demo filing" issues a real filing');
    await page.locator('#issueBtn').click();
    await page.waitForFunction(() => document.querySelectorAll('#filingCardSlot .card').length === 1, null, { timeout: 10000 });
    const filingRaw = JSON.parse(await page.locator('#filingCardSlot .card details.raw pre').textContent());
    assert(filingRaw.issuer === NODE_DOMAIN, 'expected the filing to be issued by ' + NODE_DOMAIN + ', got: ' + filingRaw.issuer);
    console.log('PASS: filing issued by', filingRaw.issuer, 'id', filingRaw.id);

    console.log('STEP 2: "Mark \'Reviewed\'" calls this same domain\'s own reviewer key and renders a real attestation signed by it');
    await page.locator('.claimBtn[data-claim="reviewed"]').click();
    await page.waitForFunction(() => document.querySelectorAll('#attestationCards .card').length === 1, null, { timeout: 10000 });
    const attestationCard = page.locator('#attestationCards .card').first();
    const attestationRaw = JSON.parse(await attestationCard.locator('details.raw pre').textContent());
    assert(attestationRaw.issuer === NODE_DOMAIN, 'expected the attestation to say issuer domain ' + NODE_DOMAIN + ', got: ' + attestationRaw.issuer);
    assert(attestationRaw.issuerKey !== filingRaw.issuerKey, 'expected the attestation to be signed by a genuinely different key than the filing, got the same issuerKey prefix for both');
    assert(attestationRaw.subject.assetId === filingRaw.id, 'expected the attestation to name the filing\'s own id as its subject');
    assert(attestationRaw.claim.toLowerCase().includes('reviewed'), 'expected the "reviewed" claim text, got: ' + attestationRaw.claim);
    console.log('PASS: attestation issued by', attestationRaw.issuer, 'with a distinct reviewer key, about', attestationRaw.subject.assetId);

    console.log('STEP 3: "Try verifying this one independently" on the attestation fetches this domain\'s reviewer key and reports valid');
    await attestationCard.locator('details.raw summary').click(); // expand the <details> to reveal the button inside it
    await attestationCard.locator('.fillVerifyBtn').click();
    const verifyResult = page.locator('#verifyResult');
    await page.waitForFunction(() => document.getElementById('verifyResult').textContent.startsWith('✓ Valid'), null, { timeout: 10000 });
    assert((await verifyResult.textContent()).includes('reviewer key'), 'expected the verify result to mention the reviewer key specifically, got: ' + (await verifyResult.textContent()));
    console.log('PASS:', await verifyResult.textContent());

    console.log('STEP 4: tampering with the pasted attestation (changing claim) correctly fails verification');
    const tampered = JSON.parse(await page.locator('#verifyInput').inputValue());
    tampered.claim = 'Something the reviewer never actually signed';
    await page.locator('#verifyInput').fill(JSON.stringify(tampered, null, 2));
    await page.locator('#verifyBtn').click();
    await page.waitForFunction(() => document.getElementById('verifyResult').textContent.startsWith('✗ Not valid'), null, { timeout: 10000 });
    assert((await verifyResult.textContent()).includes("doesn't match"), 'expected a signature-mismatch reason, got: ' + (await verifyResult.textContent()));
    console.log('PASS: a tampered attestation is correctly rejected —', await verifyResult.textContent());

    console.log('STEP 5: "Revoke this attestation" succeeds and immediately re-verifies as revoked by the reviewer key');
    // The verify panel already reads "✗ Not valid" from STEP 4's tamper
    // check, so waiting on that generic a prefix here would match the
    // stale text instantly, before revoke's own re-verify has even run —
    // wait for the specific revoked-by-reviewer-key text instead.
    await attestationCard.locator('.revokeAttBtn').click();
    await page.waitForFunction(() => document.getElementById('verifyResult').textContent.includes('revoked by') && document.getElementById('verifyResult').textContent.includes('reviewer key'), null, { timeout: 10000 });
    const revokeVerifyText = await verifyResult.textContent();
    assert(revokeVerifyText.includes('revoked by') && revokeVerifyText.includes('reviewer key'), 'expected the just-revoked attestation to independently verify as revoked by the reviewer key, got: ' + revokeVerifyText);
    assert(await attestationCard.locator('.badge.revoked').count() === 1, 'expected the attestation card to show a Revoked badge');
    console.log('PASS:', revokeVerifyText);

    console.log('STEP 6: the underlying filing itself still verifies fine — the two are genuinely independent');
    await page.locator('#filingCardSlot .card details.raw summary').click(); // expand the <details> to reveal the button inside it
    await page.locator('#filingCardSlot .card .fillVerifyBtn').click();
    await page.waitForFunction(() => document.getElementById('verifyResult').textContent.startsWith('✓ Valid'), null, { timeout: 10000 });
    assert(!(await verifyResult.textContent()).includes('reviewer key'), 'expected the filing to verify against its own key, not the reviewer key, got: ' + (await verifyResult.textContent()));
    console.log('PASS: the filing is untouched by the attestation above it being revoked —', await verifyResult.textContent());

    console.log('\nALL THIRD-PARTY ATTESTATION DEMO CHECKS PASSED (SPEC.md §5.11)');
  } catch (err) {
    console.error('FAILURE:', err);
    process.exitCode = 1;
  } finally {
    if (browser) await browser.close();
    nodeProc.kill();
    try { fs.rmSync(NODE_STATE_DIR, { recursive: true, force: true }); } catch (err) {}
    try { fs.rmSync(NODE_DOCROOT_DIR, { recursive: true, force: true }); } catch (err) {}
  }
})();
